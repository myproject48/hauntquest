#!/usr/bin/env python3
"""Copy exact resolved dependency licenses after `flutter pub get` (stdlib only)."""
import json
from pathlib import Path
import re
import urllib.parse

ROOT = Path(__file__).resolve().parent.parent
config = ROOT / '.dart_tool/package_config.json'
packages = json.loads(config.read_text())['packages']
versions = {}
name = None
for line in (ROOT / 'pubspec.lock').read_text().splitlines():
    match = re.fullmatch(r'  ([\w]+):', line)
    if match:
        name = match.group(1)
    match = re.fullmatch(r'    version: "([^"]+)"', line)
    if match and name:
        versions[name] = match.group(1)

out = ROOT / 'docs/licenses'
out.mkdir(parents=True, exist_ok=True)
texts = {}
rows = []
for package in sorted(packages, key=lambda x: x['name']):
    name = package['name']
    if name == 'hauntquest':
        continue
    uri = urllib.parse.urlparse(package['rootUri'])
    directory = (Path(urllib.parse.unquote(uri.path)) if uri.scheme == 'file'
                 else (config.parent / urllib.parse.unquote(package['rootUri'])).resolve())
    if name == 'sky_engine':
        (out / 'FLUTTER_ENGINE_LICENSES.txt').write_text((directory / 'LICENSE').read_text())
        rows.append((name, 'SDK', 'Multiple; see engine notices', 'Flutter SDK'))
        continue
    license_file = directory / 'LICENSE'
    if not license_file.exists():
        # Flutter SDK packages inherit the repository's BSD license.
        ancestor = next((p for p in directory.parents
                         if (p / 'packages/flutter_tools').is_dir()), None)
        if ancestor is None:
            raise SystemExit(f'Missing license: {name}')
        license_file = ancestor / 'LICENSE'
    text = license_file.read_text().strip()
    if 'Apache License' in text and 'Version 2.0' in text:
        kind = 'Apache-2.0'
    elif 'Permission is hereby granted, free of charge' in text:
        kind = 'MIT'
    elif 'Redistribution and use in source and binary forms' in text:
        kind = 'BSD-3-Clause'
    else:
        raise SystemExit(f'Review unrecognized license before publishing: {name}')
    texts.setdefault(text, []).append(name)
    version = versions.get(name, 'SDK')
    source = 'Flutter SDK' if '/flutter/' in str(directory) and name not in versions else f'https://pub.dev/packages/{name}/versions/{version}'
    rows.append((name, version, kind, source))

body = ['Resolved Dart/Flutter dependency licenses. Generated by tool/generate_notices.py.',
        'Third-party works retain these licenses; the project MIT license does not replace them.\n']
for text, names in texts.items():
    body.extend(['=' * 72, 'Packages: ' + ', '.join(names), '=' * 72, text, ''])
(out / 'DEPENDENCY_LICENSES.txt').write_text('\n'.join(body))
(out / 'DEPENDENCIES.md').write_text(
    '# Resolved dependency inventory\n\nGenerated from `pubspec.lock` and package license files.\n'
    'SDK packages use the checked Flutter 3.47.7 SDK. Includes development-only dependencies.\n\n'
    '| Package | Version | License | Source |\n| --- | --- | --- | --- |\n' +
    '\n'.join('| ' + ' | '.join(row) + ' |' for row in rows) + '\n')
print(f'Copied licenses for {len(rows)} resolved packages; no machine paths recorded.')
