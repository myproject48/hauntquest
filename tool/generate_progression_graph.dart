// Generates docs/PROGRESSION_GRAPH.md from the bundled content and validates
// it. Run from the project root: dart run tool/generate_progression_graph.dart
import 'dart:io';

import 'package:hauntquest/content/content_loader.dart';
import 'package:hauntquest/content/validation/content_validator.dart';
import 'package:hauntquest/content/validation/progression_graph.dart';

Future<void> main() async {
  final content = await ContentLoader.load((path) => File(path).readAsString());
  final report = ContentValidator(content).validate();
  final graph = ProgressionGraph(content);

  final out = StringBuffer()
    ..writeln('# Progression Graph: The Whispering Manor')
    ..writeln()
    ..writeln(
      'Generated by `dart run tool/generate_progression_graph.dart`. '
      'Do not edit by hand.',
    )
    ..writeln()
    ..writeln(
      'Solid arrows are required items or openings. Dashed arrows are '
      'clues the player must read. Thick arrows open a passage.',
    )
    ..writeln()
    ..writeln('```mermaid')
    ..write(graph.toMermaid())
    ..writeln('```')
    ..writeln()
    ..writeln('## Puzzle prerequisites')
    ..writeln()
    ..write(graph.dependencyTable())
    ..writeln()
    ..writeln('## Mandatory solve order (one valid order)')
    ..writeln();
  for (final (i, id) in report.dependencyOrder.indexed) {
    out.writeln('${i + 1}. ${content.puzzleById(id)?.title ?? id} (`$id`)');
  }
  out
    ..writeln()
    ..writeln('## Endings')
    ..writeln()
    ..writeln('| Ending | Example choices | Choice combinations |')
    ..writeln('|---|---|---|');
  for (final r in report.endingRoutes) {
    out.writeln(
      '| ${content.endingById(r.endingId)?.title} | '
      '${r.options.join(', ')} | ${r.leafCount} |',
    );
  }
  out
    ..writeln()
    ..writeln(
      'Validation: ${report.errors.length} errors, '
      '${report.warnings.length} warnings, '
      '${report.playthroughCount} choice combinations simulated.',
    );

  File('docs/PROGRESSION_GRAPH.md')
    ..createSync(recursive: true)
    ..writeAsStringSync(out.toString());
  stdout.writeln(report.describe());
  stdout.writeln('Wrote docs/PROGRESSION_GRAPH.md');
  if (!report.isValid) exitCode = 1;
}
